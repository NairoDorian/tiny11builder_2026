"@ -replace "`r?`n", "`r`n"

#---------[ lib\tiny11gui.psd1 (FunctionsToExport) ]---------#
Import-Module -Name (Join-Path $repo 'lib\tiny11gui.psm1') -Force -DisableNameChecking
$guiNames = @(Get-Command -Module tiny11gui | ForEach-Object { $_.Name } | Sort-Object)
$guiList = ($guiNames | ForEach-Object { "        '$_'" }) -join ",`r`n"
$outputs['lib\tiny11gui.psd1'] = @"
@{
    # Module manifest for Tiny11 Builder - Ultimate Edition : GUI module.
    # GENERATED by scripts\update-generated.ps1 - FunctionsToExport mirrors the module.
    RootModule           = 'tiny11gui.psm1'
    ModuleVersion        = '2026.9.0'
    GUID                 = 'b8a12345-1234-5678-9abc-def012345678'
    Author               = 'Tiny11 Builder Ultimate Edition contributors'
    CompanyName          = 'Tiny11 Builder'
    Description          = 'Windows Forms builder window for Tiny11 Builder - Ultimate Edition (every option, live build log).'
    PowerShellVersion    = '5.1'
    CompatiblePSEditions = @('Desktop')
    RequiredModules      = @()
    FunctionsToExport    = @(
$guiList
    )
    CmdletsToExport      = @()
    VariablesToExport    = @()
    AliasesToExport      = @()
    PrivateData          = @{
        PSData = @{
            Tags       = @('tiny11', 'windows11', 'debloat', 'gui')
            ProjectUri = 'https://github.com/NairoDorian/tiny11builder_2026'
        }
    }
}

"@ -replace "`r?`n", "`r`n"

#---------[ Write or check ]---------#
$stale = @()
$utf8 = New-Object System.Text.UTF8Encoding $false
foreach ($entry in $outputs.GetEnumerator()) {
    $path = Join-Path $repo $entry.Key
    $current = if (Test-Path $path) { [IO.File]::ReadAllText($path) } else { $null }
    $normalize = { param($s) if ($null -eq $s) { '' } else { $s -replace "`r`n", "`n" } }
    if ((& $normalize $current) -ne (& $normalize $entry.Value)) {
        $stale += $entry.Key
        if (-not $Check) {
            $encoding = if ($path -match '\.ps(m|d)?1$') { New-Object System.Text.UTF8Encoding $true } else { $utf8 }
            [IO.File]::WriteAllText($path, $entry.Value, $encoding)
            Write-Host "updated $($entry.Key)"
        }
    }
}
if ($Check) {
    if ($stale.Count) {
        Write-Host "Out of date (run scripts\update-generated.ps1): $($stale -join ', ')" -ForegroundColor Red
        exit 1
    }
    Write-Host 'Generated files are up to date.'
} elseif (-not $stale.Count) {
    Write-Host 'Nothing to update.'
}
exit 0
